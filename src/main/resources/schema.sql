-- myPaaS control-plane schema (H2, PostgreSQL-compatible subset).
-- Times are stored as epoch milliseconds so the control plane is timezone-stable and testable with a fake clock.

create table if not exists users (
    id bigint generated by default as identity primary key,
    email varchar(254) not null unique,
    display_name varchar(120) not null,
    password_hash varchar(120) not null,
    role varchar(20) not null,
    email_verified boolean not null default true,
    must_change_password boolean not null default false,
    otp_email_enabled boolean not null default true,
    notify_deployments boolean not null default true,
    notify_alerts boolean not null default true,
    created_at bigint not null
);

create table if not exists project_members (
    project_id bigint not null,
    user_id bigint not null,
    primary key (project_id, user_id)
);

create table if not exists server_members (
    server_id bigint not null,
    user_id bigint not null,
    primary key (server_id, user_id)
);

create table if not exists refresh_tokens (
    id bigint generated by default as identity primary key,
    family_id varchar(64) not null,
    user_id bigint not null,
    token_hash varchar(64) not null unique,
    expires_at bigint not null,
    revoked boolean not null default false,
    created_at bigint not null
);

create table if not exists account_tokens (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    purpose varchar(40) not null,
    token_hash varchar(64) not null unique,
    expires_at bigint not null,
    consumed boolean not null default false,
    created_at bigint not null
);

create table if not exists step_up_challenges (
    id varchar(64) primary key,
    actor_id bigint not null,
    action varchar(60) not null,
    resource_type varchar(40) not null,
    resource_id bigint,
    code_hash varchar(64) not null,
    expires_at bigint not null,
    attempts int not null default 0,
    consumed boolean not null default false,
    created_at bigint not null
);

create table if not exists step_up_grants (
    id varchar(64) primary key,
    challenge_id varchar(64) not null,
    actor_id bigint not null,
    action varchar(60) not null,
    resource_type varchar(40) not null,
    resource_id bigint,
    expires_at bigint not null,
    used boolean not null default false,
    created_at bigint not null
);

create table if not exists credentials (
    id bigint generated by default as identity primary key,
    name varchar(160) not null,
    project_id bigint,
    ciphertext bytea not null,
    wrapped_key bytea not null,
    kek_version int not null,
    created_at bigint not null,
    rotated_at bigint,
    revoked_at bigint,
    created_by bigint
);

create table if not exists servers (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    host varchar(255) not null,
    ssh_port int not null default 22,
    username varchar(120) not null,
    credential_id bigint,
    local boolean not null default false,
    os varchar(120),
    capabilities varchar(4000),
    host_key_fingerprint varchar(200),
    host_key_public varchar(1000),
    verified_at bigint,
    created_at bigint not null
);

create table if not exists projects (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    slug varchar(120) not null unique,
    description varchar(500),
    server_id bigint not null,
    latest_revision_id bigint,
    active_release_id bigint,
    tracking_key varchar(80) not null unique,
    created_at bigint not null,
    updated_at bigint not null
);

create table if not exists project_revisions (
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    revision_number int not null,
    configuration_json text not null,
    summary varchar(500),
    created_at bigint not null,
    created_by bigint,
    constraint uq_project_revision unique (project_id, revision_number)
);

create table if not exists stored_files (
    id bigint generated by default as identity primary key,
    storage_key varchar(120) not null unique,
    original_name varchar(255) not null,
    content_type varchar(160),
    size_bytes bigint not null,
    checksum_sha256 varchar(64) not null,
    sensitive boolean not null default false,
    project_id bigint,
    certificate_id bigint,
    created_at bigint not null,
    created_by bigint
);

create table if not exists certificates (
    id bigint generated by default as identity primary key,
    hostnames varchar(2000) not null,
    chain_file_id bigint not null,
    key_file_id bigint not null,
    not_before bigint not null,
    not_after bigint not null,
    uploaded_at bigint not null,
    created_by bigint
);

create table if not exists hostname_assignments (
    hostname varchar(255) primary key,
    project_id bigint not null,
    certificate_id bigint,
    created_at bigint not null,
    created_by bigint
);

create table if not exists releases (
    id bigint generated by default as identity primary key,
    deployment_id bigint not null,
    project_id bigint not null,
    server_id bigint not null,
    revision_id bigint not null,
    version varchar(80) not null,
    path varchar(500) not null,
    commit_sha varchar(80),
    created_at bigint not null
);

create table if not exists deployments (
    id bigint generated by default as identity primary key,
    project_id bigint not null,
    revision_id bigint not null,
    server_id bigint not null,
    trigger_source varchar(30) not null,
    kind varchar(20) not null default 'DEPLOY',
    job_id bigint,
    actor_id bigint,
    actor_email varchar(254),
    state varchar(40) not null,
    ref_override varchar(255),
    commit_sha varchar(80),
    failure_summary varchar(1000),
    release_id bigint,
    previous_release_id bigint,
    rollback_of bigint,
    idempotency_key varchar(160),
    cancel_requested boolean not null default false,
    created_at bigint not null,
    started_at bigint,
    finished_at bigint
);

create table if not exists deployment_logs (
    id bigint generated by default as identity primary key,
    deployment_id bigint not null,
    log_seq bigint not null,
    at_epoch_millis bigint not null,
    level varchar(20) not null,
    message text not null,
    constraint uq_deployment_log_sequence unique (deployment_id, log_seq)
);

create table if not exists deployment_steps (
    id bigint generated by default as identity primary key,
    deployment_id bigint not null,
    seq int not null,
    name varchar(60) not null,
    state varchar(20) not null,
    detail varchar(1000),
    started_at bigint not null,
    finished_at bigint
);

create table if not exists project_deployment_locks (
    project_id bigint primary key,
    deployment_id bigint not null,
    acquired_at bigint not null,
    expires_at bigint not null
);

create table if not exists idempotency_keys (
    actor_id bigint not null,
    project_id bigint not null,
    request_key varchar(160) not null,
    deployment_id bigint not null,
    created_at bigint not null,
    primary key (actor_id, project_id, request_key)
);

create table if not exists jobs (
    id bigint generated by default as identity primary key,
    type varchar(80) not null,
    payload text not null,
    idempotency_key varchar(200) unique,
    dedup_key varchar(200) unique,
    state varchar(20) not null,
    run_at bigint not null,
    attempts int not null default 0,
    max_attempts int not null default 3,
    lease_owner varchar(120),
    lease_expires_at bigint,
    last_error varchar(2000),
    correlation_id varchar(80),
    actor_id bigint,
    recurring_seconds bigint,
    cancel_requested boolean not null default false,
    created_at bigint not null,
    updated_at bigint not null,
    completed_at bigint
);

create table if not exists audit_events (
    id bigint generated by default as identity primary key,
    actor_id bigint,
    actor_email varchar(254),
    action varchar(80) not null,
    resource_type varchar(40) not null,
    resource_id bigint,
    outcome varchar(20) not null,
    correlation_id varchar(80),
    detail varchar(1000),
    created_at bigint not null
);

create table if not exists webhook_configs (
    project_id bigint primary key,
    provider varchar(30) not null,
    enabled boolean not null default false,
    allowed_events varchar(500),
    branch_filter varchar(255),
    secret_credential_id bigint,
    updated_at bigint not null,
    updated_by bigint
);

create table if not exists webhook_deliveries (
    delivery_id varchar(160) primary key,
    project_id bigint not null,
    received_at bigint not null,
    accepted boolean not null
);

create table if not exists alert_rules (
    id bigint generated by default as identity primary key,
    name varchar(160) not null,
    scope_type varchar(30) not null,
    scope_id bigint,
    metric varchar(40) not null,
    comparator varchar(10) not null,
    threshold double not null,
    cooldown_seconds int not null default 900,
    recipients varchar(1000),
    enabled boolean not null default true,
    created_at bigint not null
);

create table if not exists alert_events (
    id bigint generated by default as identity primary key,
    rule_id bigint not null,
    resource varchar(160) not null,
    state varchar(20) not null,
    detail varchar(500),
    triggered_at bigint not null,
    resolved_at bigint
);

create table if not exists notification_outbox (
    id bigint generated by default as identity primary key,
    event_type varchar(60) not null,
    recipient varchar(254) not null,
    subject varchar(300) not null,
    body text not null,
    state varchar(20) not null,
    attempts int not null default 0,
    dedup_key varchar(240) unique,
    encrypted_token bytea,
    created_at bigint not null,
    sent_at bigint,
    last_error varchar(1000)
);

create table if not exists rate_limits (
    bucket_key varchar(240) primary key,
    window_start bigint not null,
    count int not null
);

create index if not exists idx_deployments_project on deployments (project_id, created_at desc);
create index if not exists idx_deployments_state on deployments (state);
create index if not exists idx_jobs_ready on jobs (state, run_at);
create index if not exists idx_revisions_project on project_revisions (project_id, revision_number desc);
create index if not exists idx_audit_created on audit_events (created_at desc);
create index if not exists idx_releases_project on releases (project_id, created_at desc);
create index if not exists idx_steps_deployment on deployment_steps (deployment_id, seq);
create index if not exists idx_logs_deployment on deployment_logs (deployment_id, log_seq);
create index if not exists idx_files_project on stored_files (project_id, created_at desc);
create index if not exists idx_alert_events_rule on alert_events (rule_id, triggered_at desc);
